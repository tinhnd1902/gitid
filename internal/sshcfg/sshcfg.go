// Package sshcfg renders and parses the ssh configuration gitid manages.
package sshcfg

import (
	"errors"
	"fmt"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/tinhnd1902/gitid/internal/block"
	"github.com/tinhnd1902/gitid/internal/config"
)

// Header is the first line of gitid.conf.
const Header = "# Generated by gitid — DO NOT EDIT"

// IncludeLine is the directive placed in ~/.ssh/config (relative paths
// resolve against ~/.ssh).
const IncludeLine = "Include config.d/*"

// Markers delimit the managed block in ~/.ssh/config.
var Markers = block.Markers{
	Start: "# >>> gitid managed block (do not edit; run `gitid apply`) >>>",
	End:   "# <<< gitid managed block <<<",
}

// Warning codes (i18n keys).
const WarnIncludeScoped = "warn.ssh_include_scoped"

// ErrUnsafeValue means a value would allow injecting ssh config directives.
var ErrUnsafeValue = errors.New("sshcfg: unsafe value for ssh config")

var tokenRe = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]*$`)

func safeToken(s string) error {
	if !tokenRe.MatchString(s) {
		return fmt.Errorf("%w: %q", ErrUnsafeValue, s)
	}
	return nil
}

// quotePath returns p ready for use as an ssh config argument.
func quotePath(p string) (string, error) {
	for _, r := range p {
		if r < 0x20 || r == 0x7f || r == '"' || r == '%' || r == '\\' {
			return "", fmt.Errorf("%w: %q", ErrUnsafeValue, p)
		}
	}
	if p == "" {
		return "", fmt.Errorf("%w: empty path", ErrUnsafeValue)
	}
	if strings.ContainsAny(p, " \t") {
		return `"` + p + `"`, nil
	}
	return p, nil
}

// RenderHostBlock renders the Host block of an ssh-auth account.
func RenderHostBlock(c config.Company, a config.Account) (string, error) {
	alias := c.Alias(a)
	if err := safeToken(alias); err != nil {
		return "", err
	}
	host := a.EffectiveSSHHost()
	if err := safeToken(host); err != nil {
		return "", err
	}
	key := a.SSHKey
	if key == "" {
		key = c.DefaultKeyPath(a)
	}
	keyArg, err := quotePath(key)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("Host " + alias + "\n")
	b.WriteString("    HostName " + host + "\n")
	b.WriteString("    User git\n")
	if a.SSHPort > 0 {
		if a.SSHPort > 65535 {
			return "", fmt.Errorf("%w: port %d", ErrUnsafeValue, a.SSHPort)
		}
		b.WriteString("    Port " + strconv.Itoa(a.SSHPort) + "\n")
	}
	b.WriteString("    IdentityFile " + keyArg + "\n")
	b.WriteString("    IdentitiesOnly yes\n")
	b.WriteString("    AddKeysToAgent yes\n")
	b.WriteString("    IgnoreUnknown UseKeychain\n")
	b.WriteString("    UseKeychain yes\n")
	return b.String(), nil
}

// RenderGitidConf renders ~/.ssh/config.d/gitid.conf: one Host block per
// ssh-auth account, sorted by alias. It returns "" when there are none.
func RenderGitidConf(cfg config.Config) (string, error) {
	type item struct{ alias, text string }
	var items []item
	for _, ref := range cfg.All() {
		if ref.Account.Auth != config.AuthSSH {
			continue
		}
		t, err := RenderHostBlock(ref.Company, ref.Account)
		if err != nil {
			return "", err
		}
		items = append(items, item{ref.Alias(), t})
	}
	if len(items) == 0 {
		return "", nil
	}
	sort.Slice(items, func(i, j int) bool { return items[i].alias < items[j].alias })
	var b strings.Builder
	b.WriteString(Header + "\n")
	for _, it := range items {
		b.WriteString("\n" + it.text)
	}
	return b.String(), nil
}

// Aliases returns the ssh aliases gitid defines, sorted.
func Aliases(cfg config.Config) []string {
	var out []string
	for _, ref := range cfg.All() {
		if ref.Account.Auth == config.AuthSSH {
			out = append(out, ref.Alias())
		}
	}
	sort.Strings(out)
	return out
}

var (
	hostLineRe  = regexp.MustCompile(`(?i)^host(?:\s*=\s*|\s+)(.+)$`)
	matchLineRe = regexp.MustCompile(`(?i)^match(?:\s*=\s*|\s+)`)
	incLineRe   = regexp.MustCompile(`(?i)^include(?:\s*=\s*|\s+)(.+)$`)
	identRe     = regexp.MustCompile(`(?i)^identityfile(?:\s*=\s*|\s+)(.+)$`)
)

func stripQuotes(s string) string {
	s = strings.TrimSpace(s)
	if len(s) >= 2 && s[0] == '"' && s[len(s)-1] == '"' {
		return s[1 : len(s)-1]
	}
	return s
}

func stripComment(s string) string {
	if i := strings.Index(s, " #"); i >= 0 {
		s = s[:i]
	}
	return strings.TrimSpace(s)
}

func includesConfigD(args string) bool {
	for _, f := range strings.Fields(stripComment(args)) {
		switch stripQuotes(f) {
		case "config.d/*", "~/.ssh/config.d/*", "config.d/*.conf", "~/.ssh/config.d/*.conf":
			return true
		}
	}
	return false
}

// EnsureResult is the outcome of EnsureInclude.
type EnsureResult struct {
	Text     string
	Warnings []string
	// External is true when the user already has a top-level Include of
	// config.d, so no block was needed.
	External bool
}

// EnsureInclude makes sure ~/.ssh/config includes config.d/*: it puts the
// managed block at the very top, unless the user already has a global
// (before any Host/Match) Include of config.d, in which case the text is
// left alone. An Include that only appears inside a Host/Match section does
// not count and yields a warning.
func EnsureInclude(text string) (EnsureResult, error) {
	res := EnsureResult{Text: text}
	_, hasBlock, err := block.Find(text, Markers)
	if err != nil {
		return res, err
	}
	if !hasBlock {
		scoped := false
		inSection := false
		for _, raw := range strings.Split(text, "\n") {
			line := strings.TrimSpace(strings.TrimSuffix(raw, "\r"))
			if line == "" || strings.HasPrefix(line, "#") {
				continue
			}
			if hostLineRe.MatchString(line) || matchLineRe.MatchString(line) {
				inSection = true
				continue
			}
			if m := incLineRe.FindStringSubmatch(line); m != nil && includesConfigD(m[1]) {
				if !inSection {
					res.External = true
					return res, nil
				}
				scoped = true
			}
		}
		if scoped {
			res.Warnings = append(res.Warnings, WarnIncludeScoped)
		}
	}
	out, err := block.Upsert(text, IncludeLine+"\n", Markers, block.AtTop)
	if err != nil {
		return res, err
	}
	res.Text = out
	return res, nil
}

// RemoveInclude removes the managed block from ~/.ssh/config.
func RemoveInclude(text string) (string, error) { return block.Remove(text, Markers) }

// HostEntry is a Host section of a user's ssh config.
type HostEntry struct {
	Patterns     []string
	IdentityFile []string // strings only; the files are never opened
	Line         int
}

// ParseHosts lists the Host sections of text (Match sections are skipped).
// The gitid managed block is ignored.
func ParseHosts(text string) []HostEntry {
	if stripped, err := block.Remove(text, Markers); err == nil {
		text = stripped
	}
	var out []HostEntry
	cur := -1
	for n, raw := range strings.Split(text, "\n") {
		line := strings.TrimSpace(strings.TrimSuffix(raw, "\r"))
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if m := hostLineRe.FindStringSubmatch(line); m != nil {
			var pats []string
			for _, f := range strings.Fields(stripComment(m[1])) {
				pats = append(pats, stripQuotes(f))
			}
			out = append(out, HostEntry{Patterns: pats, Line: n + 1})
			cur = len(out) - 1
			continue
		}
		if matchLineRe.MatchString(line) {
			cur = -1
			continue
		}
		if cur >= 0 {
			if m := identRe.FindStringSubmatch(line); m != nil {
				out[cur].IdentityFile = append(out[cur].IdentityFile, stripQuotes(stripComment(m[1])))
			}
		}
	}
	return out
}

// HostPatterns flattens all Host patterns (excluding negations and
// wildcards-only sections are kept; callers compare exact names).
func HostPatterns(entries []HostEntry) []string {
	var out []string
	for _, e := range entries {
		out = append(out, e.Patterns...)
	}
	return out
}
