// Header is the first line of every file gitid generates.
const Header = "# Generated by gitid — DO NOT EDIT"

// Markers delimit the managed block in ~/.gitconfig.
var Markers = block.Markers{
	Start: "# >>> gitid managed block (do not edit; run `gitid apply`) >>>",
	End:   "# <<< gitid managed block <<<",
}

// ErrUnsafeValue means a value contains characters that cannot be written
// to a gitconfig file safely.
var ErrUnsafeValue = errors.New("gitcfg: value contains control characters or newlines")

// IsGenerated reports whether content starts with the gitid header.
func IsGenerated(content string) bool {
	first, _, _ := strings.Cut(content, "\n")
	return strings.HasPrefix(strings.TrimSpace(first), "# Generated by gitid")
}

func hasControl(s string) bool {
	for _, r := range s {
		if r < 0x20 || r == 0x7f || r == ' ' || r == ' ' {
			return true
		}
	}
	return false
}

// Escape renders s as a git config value, quoting and escaping when needed.
func Escape(s string) (string, error) {
	if hasControl(s) {
		return "", ErrUnsafeValue
	}
	needQuote := s != strings.TrimSpace(s) || strings.ContainsAny(s, "#;\"\\")
	if !needQuote {
		return s, nil
	}
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `"`, `\"`)
	return `"` + s + `"`, nil
}

// subsection renders a quoted subsection name for [includeIf "..."].
func subsection(s string) (string, error) {
	if hasControl(s) || strings.ContainsAny(s, "\"\\") {
		return "", ErrUnsafeValue
	}
	return s, nil
}

// AccountFile returns the path of the generated user file of an account.
func AccountFile(e env.Env, c config.Company, a config.Account) string {
	return filepath.Join(e.Paths().GitDir, c.KeyBase(a)+".gitconfig")
}

// CompanyFile returns the path of the company dispatcher file.
func CompanyFile(e env.Env, c config.Company) string {
	return filepath.Join(e.Paths().GitDir, c.Slug+".gitconfig")
}

// RenderAccountFile renders [user] name/email for an account.
func RenderAccountFile(a config.Account) (string, error) {
	name, err := Escape(a.Name)
	if err != nil {
		return "", fmt.Errorf("name: %w", err)
	}
	email, err := Escape(a.Email)
	if err != nil {
		return "", fmt.Errorf("email: %w", err)
	}
	return Header + "\n[user]\n\tname = " + name + "\n\temail = " + email + "\n", nil
}

func includeIf(cond, path string) (string, error) {
	cond, err := subsection(cond)
	if err != nil {
		return "", err
	}
	p, err := Escape(path)
	if err != nil {
		return "", err
	}
	return "[includeIf \"" + cond + "\"]\n\tpath = " + p + "\n", nil
}

// RenderCompanyFile renders the company dispatcher: the default account is
// included unconditionally, then every account's hasconfig includes follow
// (later includes win).
func RenderCompanyFile(e env.Env, c config.Company) (string, error) {
	var b strings.Builder
	b.WriteString(Header + "\n")
	if def, ok := c.Default(); ok {
		p, err := Escape(e.Contract(AccountFile(e, c, def)))
		if err != nil {
			return "", err
		}
		b.WriteString("[include]\n\tpath = " + p + "\n")
	}
	for _, a := range c.Accounts {
		ref := config.AccountRef{Company: c, Account: a}
		path := e.Contract(AccountFile(e, c, a))
		for _, pat := range remote.Patterns(ref) {
			s, err := includeIf("hasconfig:remote.*.url:"+pat, path)
			if err != nil {
				return "", err
			}
			b.WriteString(s)
		}
	}
	return b.String(), nil
}

// PatternEntry is one globally-applicable hasconfig pattern.
type PatternEntry struct {
	Ref     config.AccountRef
	Pattern string
}

// Ambiguity is a hasconfig pattern produced by more than one account.
type Ambiguity struct {
	Pattern  string
	Accounts []string // "company/account"
}

// GlobalPatterns splits every account's patterns into those unique across
// all companies (safe outside any base dir) and those shared by several
// accounts (omitted globally). Both lists follow config order.
func GlobalPatterns(cfg config.Config) (unique []PatternEntry, ambiguous []Ambiguity) {
	owners := map[string][]string{}
	var all []PatternEntry
	for _, ref := range cfg.All() {
		for _, p := range remote.Patterns(ref) {
			owners[p] = append(owners[p], ref.String())
			all = append(all, PatternEntry{Ref: ref, Pattern: p})
		}
	}
	seen := map[string]bool{}
	for _, pe := range all {
		if len(owners[pe.Pattern]) == 1 {
			unique = append(unique, pe)
		} else if !seen[pe.Pattern] {
			seen[pe.Pattern] = true
			ambiguous = append(ambiguous, Ambiguity{Pattern: pe.Pattern, Accounts: owners[pe.Pattern]})
		}
	}
	return unique, ambiguous
}

// RenderManagedBody renders the inner content of the ~/.gitconfig managed
// block. It is empty when no company has an account (the block is then
// removed, D16).
func RenderManagedBody(e env.Env, cfg config.Config) (string, error) {
	var b strings.Builder
	for _, c := range cfg.Companies {
		if len(c.Accounts) == 0 {
			continue
		}
		cond := "gitdir:" + e.Contract(e.Expand(c.BaseDir))
		if !strings.HasSuffix(cond, "/") {
			cond += "/"
		}
		s, err := includeIf(cond, e.Contract(CompanyFile(e, c)))
		if err != nil {
			return "", err
		}
		b.WriteString(s)
	}
	unique, _ := GlobalPatterns(cfg)
	if len(unique) > 0 {
		b.WriteString("# global (outside base dirs): only patterns unique across all companies\n")
	}
	for _, pe := range unique {
		s, err := includeIf("hasconfig:remote.*.url:"+pe.Pattern, e.Contract(AccountFile(e, pe.Ref.Company, pe.Ref.Account)))
		if err != nil {
			return "", err
		}
		b.WriteString(s)
	}
	return b.String(), nil
}
