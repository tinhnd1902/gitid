		"[includeIf \"hasconfig:remote.*.url:ssh://git@github-acme-carol/**\"]\n\tpath = " + g + "acme-carol.gitconfig\n" +
		"[includeIf \"hasconfig:remote.*.url:ssh://github-acme-carol/**\"]\n\tpath = " + g + "acme-carol.gitconfig\n"
	if got != want {
		t.Fatalf("got:\n%s\nwant:\n%s", got, want)
	}
	// no default account: no unconditional include
	c := fixtures.Acme()
	c.DefaultAccount = ""
	got, _ = gitcfg.RenderCompanyFile(e, c)
