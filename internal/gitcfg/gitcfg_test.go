func TestG8ParseIncludeIfs(t *testing.T) {
	got := gitcfg.ParseIncludeIfs(userGitconfig)
	if len(got) != 1 {
		t.Fatalf("%+v", got)
	}
	i := got[0]
	if i.Condition != "gitdir:~/Code/work/main-job/initech-solutions/" || i.Path != "~/.gitconfig-initech" || i.Kind() != "gitdir" || i.Target() != "~/Code/work/main-job/initech-solutions/" || i.Line != 9 {
		t.Fatalf("%+v", i)
	}
	// entries inside the managed block are ignored
	e := testutil.TempEnv(t)
	body, _ := gitcfg.RenderManagedBody(e, fixtures.Basic())
	text, _ := block.Upsert(userGitconfig, body, gitcfg.Markers, block.AtEnd)
	if got := gitcfg.ParseIncludeIfs(text); len(got) != 1 {
		t.Fatalf("block entries leaked: %+v", got)
	}
	// odd syntax
	odd := "[includeif \"gitdir/i:~/X/\"] # c\n  path = \"~/a b\" # tail\n[other]\n  path = nope\n[includeIf \"hasconfig:remote.*.url:**\"]\n\tpath=~/h\r\n[core]\n"
	got = gitcfg.ParseIncludeIfs(odd)
	if len(got) != 2 || got[0].Kind() != "gitdir/i" || got[0].Path != "~/a b" || got[1].Kind() != "hasconfig" || got[1].Path != "~/h" {
		t.Fatalf("%+v", got)
	}
	// corrupt block markers: parsing still works on the raw text
	corrupt := gitcfg.Markers.Start + "\n[includeIf \"gitdir:~/Y/\"]\n\tpath = ~/y\n"
	if got := gitcfg.ParseIncludeIfs(corrupt); len(got) != 1 {
		t.Fatalf("%+v", got)
	}
	if (gitcfg.IncludeIf{Condition: "nocolon"}).Target() != "" {
		t.Fatal("target")
	}
}

func TestG9Version(t *testing.T) {
	cases := []struct {
		in   string
		want gitcfg.Version
		ok   bool
	}{
		{"git version 2.56.0", gitcfg.Version{2, 56, 0}, true},
		{"git version 2.39.5 (Apple Git-154)", gitcfg.Version{2, 39, 5}, true},
		{"git version 2.36.0.windows.1", gitcfg.Version{2, 36, 0}, true},
		{"git version 2.36", gitcfg.Version{2, 36, 0}, true},
		{"garbage", gitcfg.Version{}, false},
		{"", gitcfg.Version{}, false},
	}
	for _, c := range cases {
		v, err := gitcfg.ParseVersion(c.in)
		if (err == nil) != c.ok || v != c.want {
			t.Errorf("%q: %v %v", c.in, v, err)
		}
	}
	v, _ := gitcfg.ParseVersion("git version 2.35.1")
	if v.AtLeast(2, 36) || !(gitcfg.Version{2, 36, 0}).AtLeast(2, 36) || !(gitcfg.Version{3, 0, 0}).AtLeast(2, 36) || v.String() != "2.35.1" {
		t.Fatal("AtLeast")
	}
	if !gitcfg.MinGitVersion.AtLeast(2, 36) {
		t.Fatal("min version")
	}
}

func TestParseUser(t *testing.T) {
	text := "[core]\n\tname = notme\n[user]\n\tname = \"O\\\"Brien \\\\ x\" # c\n\temail = x@initech.example ; trailing\n[USER]\n  email=last@x.io\n[other]\n\temail = nope\n"
	n, e := gitcfg.ParseUser(text)
	if n != `O"Brien \ x` || e != "last@x.io" {
		t.Fatalf("%q %q", n, e)
	}
	if n, e := gitcfg.ParseUser(""); n != "" || e != "" {
		t.Fatal("empty")
	}
	// round trip with the renderer
	out, _ := gitcfg.RenderAccountFile(fixtures.Acme().Accounts[0])
	if n, e := gitcfg.ParseUser(out); n != "Alice Nguyen" || e != "alice@acme.com" {
		t.Fatalf("%q %q", n, e)
	}
	tricky, _ := gitcfg.RenderAccountFile(config.Account{Name: `a "b" #c; d\e`, Email: "x@y.z"})
	if n, _ := gitcfg.ParseUser(tricky); n != `a "b" #c; d\e` {
		t.Fatalf("%q", n)
	}
	if n, _ := gitcfg.ParseUser("[user]\n\tname = \"unterminated\n"); n != "unterminated" {
		t.Fatalf("%q", n)
	}
}
