package gitcfg_test

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// This is the T3 spike: a hand-written copy of the layout in plan section 3.4,
// checked against the real git binary. It is offline (git init + git remote
// add only, never fetch) and uses an isolated HOME / GIT_CONFIG_GLOBAL.

type spike struct {
	t    *testing.T
	home string
}

func newSpike(t *testing.T) *spike {
	t.Helper()
	home, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	return &spike{t: t, home: home}
}

func (s *spike) git(dir string, args ...string) (string, error) {
	cmd := exec.Command("git", args...)
	cmd.Dir = dir
	cmd.Env = []string{
		"PATH=" + os.Getenv("PATH"),
		"HOME=" + s.home,
		"XDG_CONFIG_HOME=" + filepath.Join(s.home, ".config"),
		"GIT_CONFIG_GLOBAL=" + filepath.Join(s.home, ".gitconfig"),
		"GIT_CONFIG_NOSYSTEM=1",
		"LANG=C",
	}
	out, err := cmd.CombinedOutput()
	return strings.TrimSpace(string(out)), err
}

func (s *spike) write(rel, content string) {
	s.t.Helper()
	p := filepath.Join(s.home, rel)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		s.t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		s.t.Fatal(err)
	}
}

func (s *spike) repo(rel string, remotes ...string) string {
	s.t.Helper()
	dir := filepath.Join(s.home, rel)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		s.t.Fatal(err)
	}
	if out, err := s.git(dir, "init", "-q"); err != nil {
		s.t.Fatalf("git init: %v %s", err, out)
	}
	for i := 0; i+1 < len(remotes); i += 2 {
		if out, err := s.git(dir, "remote", "add", remotes[i], remotes[i+1]); err != nil {
			s.t.Fatalf("remote add: %v %s", err, out)
		}
	}
	return dir
}

func acctFile(name, email string) string {
	return "# Generated by gitid\n[user]\n\tname = " + name + "\n\temail = " + email + "\n"
}

func TestSpikeLayout(t *testing.T) {
	s := newSpike(t)
	g := "~/.config/gitid/git/"
	s.write(".config/gitid/git/acme-alice.gitconfig", acctFile("Alice", "alice@acme.com"))
	s.write(".config/gitid/git/acme-bob.gitconfig", acctFile("Bob", "bob@acme.com"))
	s.write(".config/gitid/git/acme-carol.gitconfig", acctFile("Carol", "carol@acme.com"))
	s.write(".config/gitid/git/acme-ab.gitconfig", acctFile("AB", "ab@corp.com"))
	s.write(".config/gitid/git/beta-alice.gitconfig", acctFile("Alice B", "alice@beta.io"))

	carolPats := []string{
		"git@github-acme-carol:*/**",
		"github-acme-carol:*/**",
		"ssh://git@github-acme-carol/**",
		"ssh://github-acme-carol/**",
	}
	inc := func(pat, path string) string {
		return "[includeIf \"hasconfig:remote.*.url:" + pat + "\"]\n\tpath = " + path + "\n"
	}
	acme := "[include]\n\tpath = " + g + "acme-alice.gitconfig\n" +
		inc("https://bob@github.com/**", g+"acme-bob.gitconfig") +
		inc("https://a.b%40corp.com@github.com/**", g+"acme-ab.gitconfig")
	for _, p := range carolPats {
		acme += inc(p, g+"acme-carol.gitconfig")
	}
	acme += inc("https://alice@github.com/**", g+"acme-alice.gitconfig")
	s.write(".config/gitid/git/acme.gitconfig", acme)
	s.write(".config/gitid/git/beta.gitconfig",
		"[include]\n\tpath = "+g+"beta-alice.gitconfig\n"+
			inc("https://alice@github.com/**", g+"beta-alice.gitconfig"))

	gc := "[user]\n\tname = Global\n\temail = global@x.io\n" +
		"# >>> gitid managed block (do not edit; run `gitid apply`) >>>\n" +
		"[includeIf \"gitdir:~/Code/acme/\"]\n\tpath = " + g + "acme.gitconfig\n" +
		"[includeIf \"gitdir:~/Code/beta/\"]\n\tpath = " + g + "beta.gitconfig\n"
	for _, p := range carolPats {
		gc += inc(p, g+"acme-carol.gitconfig")
	}
	gc += inc("https://bob@github.com/**", g+"acme-bob.gitconfig")
	gc += "# <<< gitid managed block <<<\n"
	s.write(".gitconfig", gc)

	type tc struct {
		name, dir string
		remotes   []string
		want      string
	}
	cases := []tc{
		{"GI1 default", "Code/acme/r1", nil, "alice@acme.com"},
		{"GI2 bob https", "Code/acme/r2", []string{"origin", "https://bob@github.com/o/r.git"}, "bob@acme.com"},
		{"GI3 carol scp", "Code/acme/r3", []string{"origin", "git@github-acme-carol:o/r.git"}, "carol@acme.com"},
		{"GI4 carol nested", "Code/acme/r4", []string{"origin", "git@github-acme-carol:group/sub/r.git"}, "carol@acme.com"},
		{"GI5 carol ssh://", "Code/acme/r5", []string{"origin", "ssh://git@github-acme-carol/o/r.git"}, "carol@acme.com"},
		{"GI6 beta alice", "Code/beta/r1", []string{"origin", "https://alice@github.com/o/r.git"}, "alice@beta.io"},
		{"GI7 acme alice", "Code/acme/r6", []string{"origin", "https://alice@github.com/o/r.git"}, "alice@acme.com"},
		{"GI8 outside carol", "outside/r", []string{"origin", "git@github-acme-carol:o/r.git"}, "carol@acme.com"},
		{"GI9 outside alice ambiguous", "outside/r2", []string{"origin", "https://alice@github.com/o/r.git"}, "global@x.io"},
		{"GI10 outside none", "outside/r3", nil, "global@x.io"},
		{"GI11 percent-encoded user", "Code/acme/r7", []string{"origin", "https://a.b%40corp.com@github.com/o/r.git"}, "ab@corp.com"},
		// GI12: with two matching remotes, the include read LAST wins. The global
		// section of ~/.gitconfig is read after the company files, so bob (a
		// globally-unique pattern, listed last in the block) beats carol here.
		// Plan expected carol; the plan said "document the order". Documented.
		{"GI12 two remotes: global section is read last", "Code/acme/r8", []string{"origin", "https://bob@github.com/o/r.git", "upstream", "git@github-acme-carol:o/r.git"}, "bob@acme.com"},
		{"GI12b company-only pattern loses to global alias", "Code/acme/r12", []string{"origin", "https://alice@github.com/o/r.git", "upstream", "git@github-acme-carol:o/r.git"}, "carol@acme.com"},
		{"extra: ssh://alias without git@", "Code/acme/r9", []string{"origin", "ssh://github-acme-carol/o/r.git"}, "carol@acme.com"},
		{"extra: bare alias scp", "Code/acme/r10", []string{"origin", "github-acme-carol:o/r.git"}, "carol@acme.com"},
		{"extra: outside bob", "outside/r4", []string{"origin", "https://bob@github.com/o/r.git"}, "bob@acme.com"},
		{"extra: other user not matched", "Code/acme/r11", []string{"origin", "https://zed@github.com/o/r.git"}, "alice@acme.com"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			dir := s.repo(c.dir, c.remotes...)
			got, err := s.git(dir, "config", "user.email")
			if err != nil || got != c.want {
				t.Fatalf("user.email = %q (err %v), want %q", got, err, c.want)
			}
			// GI-negative: git must not complain about remote URLs in included files.
			if out, err := s.git(dir, "config", "--list"); err != nil {
				t.Fatalf("git config --list failed: %v\n%s", err, out)
			}
		})
	}
}

// Pattern semantics: "git@alias:**" must NOT match "org/repo" scp-style URLs
// while "git@alias:*/**" must (plan section 3.3).
func TestSpikePatternSemantics(t *testing.T) {
	s := newSpike(t)
	s.write("inc.gitconfig", "[user]\n\temail = hit@x.io\n")
	for _, pat := range []struct {
		pattern, url string
		match        bool
	}{
		{"git@h:*/**", "git@h:org/repo.git", true},
		{"git@h:*/**", "git@h:a/b/c/repo.git", true},
		{"git@h:**", "git@h:org/repo.git", false},
		{"git@h:*", "git@h:org/repo.git", false},
		{"https://u@github.com/**", "https://u@github.com/o/r.git", true},
		{"https://u@github.com/**", "https://v@github.com/o/r.git", false},
	} {
		s.write(".gitconfig", "[user]\n\temail = miss@x.io\n[includeIf \"hasconfig:remote.*.url:"+pat.pattern+"\"]\n\tpath = ~/inc.gitconfig\n")
		dir := s.repo("p/"+strings.NewReplacer("/", "_", ":", "_", "@", "_", "*", "S").Replace(pat.pattern+pat.url), "origin", pat.url)
		got, err := s.git(dir, "config", "user.email")
		if err != nil {
			t.Fatal(err)
		}
		want := "miss@x.io"
		if pat.match {
			want = "hit@x.io"
		}
		if got != want {
			t.Errorf("pattern %q url %q: got %q want %q", pat.pattern, pat.url, got, want)
		}
	}
}
